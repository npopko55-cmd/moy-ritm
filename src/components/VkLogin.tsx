/**
 * Кнопка «Войти через ВКонтакте» над формами входа и регистрации.
 *
 * Регистрация и вход — одна кнопка: нет аккаунта — бэкенд его создаст, есть
 * (по VK или по той же почте) — впустит в него. Строка о согласии стоит
 * прямо под кнопкой: нажатие — согласие на обработку ПД (152-ФЗ), бэкенд
 * отмечает его у нового аккаунта.
 */

import { Link, useSearchParams } from 'react-router-dom'
import { VK_LOGIN_AVAILABLE, vkErrorText, vkStartUrl } from '../lib/vkid'
import './VkLogin.css'

type Props = {
  /** Куда вернуть человека после входа — путь сайта. */
  next: string
  /** Подпись под кнопкой: «или почтой» после кнопки. */
  dividerText?: string
}

export default function VkLogin({ next, dividerText = 'или по почте' }: Props) {
  // Вход через VK не удался — колбэк вернул сюда с ?vk_error=<код>. Текст —
  // над кнопкой, а не под формой: на телефоне низ формы за краем экрана.
  const [params] = useSearchParams()
  const vkError = vkErrorText(params.get('vk_error'))
  if (!VK_LOGIN_AVAILABLE) return null
  return (
    <div className="vk-login">
      {vkError && (
        <p className="vk-login__error" role="alert" data-testid="vk-error">
          {vkError}
        </p>
      )}
      <a className="vk-login__btn" href={vkStartUrl(next)} data-testid="vk-login">
        <svg className="vk-login__logo" viewBox="0 0 24 24" aria-hidden="true" width="24" height="24">
          <path
            fill="currentColor"
            d="M12.785 16.241s.288-.032.436-.194c.136-.148.132-.427.132-.427s-.02-1.304.576-1.496c.588-.19 1.341 1.26 2.14 1.818.605.422 1.064.33 1.064.33l2.137-.03s1.117-.071.587-.964c-.043-.073-.308-.661-1.588-1.87-1.34-1.264-1.16-1.059.453-3.246.983-1.332 1.376-2.145 1.253-2.493-.117-.332-.84-.244-.84-.244l-2.406.015s-.178-.025-.31.056c-.13.079-.212.262-.212.262s-.382 1.03-.89 1.907c-1.07 1.85-1.499 1.948-1.674 1.832-.407-.267-.305-1.075-.305-1.648 0-1.793.267-2.54-.521-2.733-.262-.065-.454-.107-1.123-.114-.858-.009-1.585.003-1.996.208-.274.136-.485.44-.356.457.159.022.519.099.71.363.246.341.237 1.107.237 1.107s.142 2.11-.33 2.371c-.325.18-.77-.187-1.725-1.865-.489-.859-.859-1.81-.859-1.81s-.07-.176-.198-.272c-.154-.115-.37-.151-.37-.151l-2.286.015s-.343.01-.469.161C3.94 7.721 4.043 8 4.043 8s1.79 4.258 3.817 6.403c1.858 1.967 3.968 1.838 3.968 1.838h.957z"
          />
        </svg>
        Войти через ВКонтакте
      </a>
      <p className="vk-login__note">
        Нажимая, вы даёте <Link to="/consent">согласие</Link> на обработку персональных данных
      </p>
      <div className="vk-login__or" role="separator">
        <span>{dividerText}</span>
      </div>
    </div>
  )
}
