/**
 * Разблокировка медиа в касании.
 *
 * Вьюха Telegram на iPhone запускает звук и видео только из обработчика
 * касания, а ролики и музыка у нас стартуют позже — через пять секунд
 * отсчёта и из эффектов. Поэтому в самом касании «Влиться в поток» (и
 * остальных кнопок, ведущих в тренировку) каждый медиа-элемент один раз
 * запускается и останавливается: дальше WebKit позволяет запускать его из
 * кода. Человек этого не видит и не слышит.
 *
 * Звать синхронно, первой строкой обработчика: после await или таймера
 * касания для WebKit уже нет. Повторные вызовы почти ничего не стоят —
 * разблокированное второй раз не трогается. В Chrome, Safari на Mac и на
 * Android ничего не меняется: там это короткий пуск и остановка.
 */

import { unlockVideos } from './videoPool'

/** Разблокировка музыки. Её ставит MusicProvider: проигрыватель живёт там. */
let unlockMusic: (() => void) | null = null

export function setMusicUnlock(unlock: (() => void) | null): void {
  unlockMusic = unlock
}

export function unlockMedia(): void {
  try {
    unlockVideos()
    unlockMusic?.()
  } catch {
    /* разблокировка — подстраховка: кнопка должна сработать в любом случае */
  }
}
