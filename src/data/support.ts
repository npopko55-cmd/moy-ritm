/**
 * Telegram поддержки.
 *
 * Значение **дублирует настройку сервера** SUPPORT_TELEGRAM_URL, и это не
 * недосмотр: гостю `me` недоступен, а кнопка «Написать в Telegram» нужна и
 * ему — человек может прийти на /help до всякого входа. Вошедшему адрес
 * берётся из профиля (`me.support.telegram_url`), и настоящий источник
 * правды — сервер: поменяли там — поменялось у всех вошедших. Эта константа
 * остаётся запасным вариантом для гостя, менять её нужно вместе с сервером.
 */
export const TELEGRAM_URL = 'https://t.me/dmitry_kirichenko'

/**
 * Заглушка почты поддержки.
 *
 * Такой ящик заведён в настройках сервера, но не существует на самом деле:
 * письмо на него никуда не придёт. Пока это так, адрес нигде не показываем —
 * обещать ответ на несуществующую почту хуже, чем не показать её вовсе.
 */
export const PLACEHOLDER_EMAIL = 'support@ritmritm.ru'

/** Настоящий ли адрес поддержки: заглушку и пустое значение не показываем. */
export function realSupportEmail(email: string | null | undefined): string | null {
  const value = (email || '').trim()
  return value && value.toLowerCase() !== PLACEHOLDER_EMAIL ? value : null
}
